/** Every entry exactly once, in category order (recommend first). */
export const ALL_EMOJIS: readonly EmojiEntry[] = EMOJI_CATEGORIES.flatMap((category) => category.emojis)

/**
 * Matches a keyword substring (Chinese or English) or the character itself.
 * An empty query returns nothing: the picker shows a category instead.
 */
export function searchEmojis(query: string): EmojiEntry[] {
  const needle = query.trim().toLowerCase()
  if (!needle) return []
  const seen = new Set<string>()
  const matches: EmojiEntry[] = []
  for (const entry of ALL_EMOJIS) {
    if (seen.has(entry.char)) continue
    if (entry.char === needle || entry.keywords.toLowerCase().includes(needle)) {
      seen.add(entry.char)
      matches.push(entry)
    }
  }
  return matches
}